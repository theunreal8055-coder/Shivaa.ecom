#!/usr/bin/env python3
"""v246 — build ONE script request out of the 31 behaviour layers.

WHY
---
index.html asked for 33 separate <script> files: app.js (812 KB) plus 31
layers (otp-autofill, hallmark, trust, auth, v107 … v245). Every one is a small
IIFE that patches the app after it has booted, and every one is a separate
round trip on a phone:

  · 33 requests on a 4G link is ~33 × RTT of pure waiting before the last layer
    can run, and `defer` means they execute strictly in order — one slow reply
    in the middle delays every layer behind it;
  · each file has its own gzip dictionary, so 31 small files compress far worse
    than the same bytes together.

So the 31 layers become `cms/js/rel.js`, one file, loaded right after app.js.
`app.js` deliberately stays on its own: it is the application, and if a layer
ever breaks, the shop must still open. The layers are pure enhancements
(scroll, ripples, guards, diagnostics) — the failure boundary belongs there.

WHAT THIS DOES
  · reads the order from tools/js-bundle-order.txt (document order, preserved
    exactly — later layers deliberately patch earlier ones);
  · writes cms/js/rel.js with a provenance comment per file;
  · verifies the output parses (node --check) and that every input file is
    present exactly once;
  · verifies index.html loads exactly app.js + rel.js.

WHAT IT DOES NOT DO
  · It never edits or deletes a layer. They stay in the repo and in the zip
    (the QA suites read them, and a rollback restores index.html alone).
  · No minification: the layers are IIFEs already, and gzip does the rest.

USAGE
  python3 tools/build-js-bundle.py            # dry run: report only
  python3 tools/build-js-bundle.py --write    # write cms/js/rel.js
    # then: python3 tools/make-rel-tag.py --write   (rewrites index.html's tags)
"""
import io
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CMS = os.path.join(ROOT, 'cms')
JS = os.path.join(CMS, 'js')
ORDER = os.path.join(ROOT, 'tools', 'js-bundle-order.txt')
OUT = os.path.join(JS, 'rel.js')
INDEX = os.path.join(CMS, 'index.html')

HEADER = """/* ═══════════════════════════════════════════════════════════════════════
   SHIVAA · rel.js — every behaviour layer, one request (v246)
   Generated by tools/build-js-bundle.py from tools/js-bundle-order.txt.
   DO NOT EDIT THIS FILE: edit the layer under cms/js/ and rebuild.
   Order is document order and is load-bearing — later layers patch earlier
   ones on purpose. app.js is NOT in here: it is the application, and a layer
   may never be able to stop the shop from opening.
   ═══════════════════════════════════════════════════════════════════════ */
"""


def order():
    names = []
    for line in io.open(ORDER, encoding='utf-8'):
        line = line.strip()
        if line and not line.startswith('#'):
            names.append(line)
    return names


def build():
    names = order()
    missing = [n for n in names if not os.path.isfile(os.path.join(JS, n))]
    if missing:
        raise SystemExit('missing layer(s): ' + ', '.join(missing))
    if len(set(names)) != len(names):
        raise SystemExit('a layer is listed twice in ' + os.path.relpath(ORDER, ROOT))
    if 'app.js' in names:
        raise SystemExit('app.js must never be bundled into rel.js')
    parts = [HEADER]
    total = 0
    for n in names:
        src = io.open(os.path.join(JS, n), encoding='utf-8').read()
        total += len(src.encode('utf-8'))
        parts.append('\n/* ─────────── %s ─────────── */\n' % n)
        parts.append(src if src.endswith('\n') else src + '\n')
    body = ''.join(parts)
    return names, body, total


def main():
    write = '--write' in sys.argv
    names, body, total = build()
    out_b = len(body.encode('utf-8'))
    print(' layers bundled      : %d' % len(names))
    print(' source bytes        : %d (%.1f KB)' % (total, total / 1024.0))
    print(' rel.js bytes        : %d (%.1f KB)' % (out_b, out_b / 1024.0))

    # a bundle that does not parse breaks every layer at once: prove it
    tmp = os.path.join(JS, '.rel-check.js')
    io.open(tmp, 'w', encoding='utf-8').write(body)
    r = subprocess.run(['node', '--check', tmp], capture_output=True, text=True)
    os.remove(tmp)
    if r.returncode != 0:
        raise SystemExit('REFUSING: the bundle does not parse\n' + r.stderr[:2000])
    print(' node --check        : OK')

    # index.html must ask for app.js + rel.py — nothing else
    idx = io.open(INDEX, encoding='utf-8').read()
    srcs = re.findall(r'<script src="/js/([^"?]+)\?v=\d+" defer></script>', idx)
    stray = [s for s in srcs if s not in ('app.js', 'rel.js')]
    print(' index.html requests : %s' % ', '.join(srcs))
    if stray:
        print(' WARNING             : %d layer tag(s) still in index.html: %s' % (len(stray), ', '.join(stray)))

    if not write:
        print('\n dry run — re-run with --write')
        return
    io.open(OUT, 'w', encoding='utf-8').write(body)
    print('\n wrote %s' % os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
